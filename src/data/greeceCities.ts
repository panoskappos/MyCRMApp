/**
 * Map of Latin uppercase characters to their Greek equivalents for search.
 */
const latinToGreekMap: Record<string, string> = {
  'A': 'Α', 'B': 'Β', 'C': 'Σ', 'D': 'Δ', 'E': 'Ε', 'F': 'Φ',
  'G': 'Γ', 'H': 'Η', 'I': 'Ι', 'J': 'ΤΖ', 'K': 'Κ', 'L': 'Λ',
  'M': 'Μ', 'N': 'Ν', 'O': 'Ο', 'P': 'Π', 'Q': 'Κ', 'R': 'Ρ',
  'S': 'Σ', 'T': 'Τ', 'U': 'Υ', 'V': 'Β', 'W': 'Ω', 'X': 'Χ',
  'Y': 'Υ', 'Z': 'Ζ'
};

/**
 * Normalizes Greek text for search matching by converting to uppercase,
 * removing diacritics/accents, and converting Latin lookalikes to Greek.
 */
export function normalizeGreekSearch(text: string): string {
  if (!text) return "";
  
  const normalized = text.toUpperCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  let result = "";
  
  for (let i = 0; i < normalized.length; i++) {
    const char = normalized[i];
    result += latinToGreekMap[char] || char;
  }

  return result.trim();
}

/**
 * Filters the city list based on user query string.
 */
export function filterCities(query: string, cityList: string[] = GREEK_CITIES): string[] {
  if (!query.trim()) return cityList;
  const normalizedQuery = normalizeGreekSearch(query);
  return cityList.filter(city => {
    const normalizedCity = normalizeGreekSearch(city);
    return normalizedCity.includes(normalizedQuery);
  });
}
